"""Generates a production-grade voice agent project from an agent configuration."""

from __future__ import annotations

import io
import zipfile
from typing import Any


def generate_project(config: dict[str, Any], project_name: str = "voice-agent") -> bytes:
    """Generate a complete voice agent project as a ZIP file."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr(f"{project_name}/pyproject.toml", _pyproject_toml(project_name, config))
        zf.writestr(f"{project_name}/README.md", _readme(project_name, config))
        zf.writestr(f"{project_name}/agent.py", _agent_py(config))
        zf.writestr(f"{project_name}/server.py", _server_py(config))
        zf.writestr(f"{project_name}/providers/__init__.py", "")
        zf.writestr(f"{project_name}/providers/stt.py", _stt_adapter(config))
        zf.writestr(f"{project_name}/providers/tts.py", _tts_adapter(config))
        zf.writestr(f"{project_name}/providers/llm.py", _llm_adapter(config))
        zf.writestr(f"{project_name}/providers/vad.py", _vad_adapter(config))
        zf.writestr(f"{project_name}/config.yaml", _config_yaml(config))
        zf.writestr(f"{project_name}/.env.example", _env_example(config))
        zf.writestr(f"{project_name}/.gitignore", _gitignore())
    return buf.getvalue()


def _pyproject_toml(name: str, config: dict) -> str:
    stt = config.get("stt", "deepgram")
    tts = config.get("tts", "elevenlabs")
    llm = config.get("llm", "openai")
    deps = [
        '"websockets>=17.0"',
        '"python-dotenv>=1.2.2"',
        '"pyyaml>=6.0"',
        '"structlog>=24.0"',
    ]
    if stt == "deepgram":
        deps.append('"deepgram-sdk>=3.0"')
    if tts == "elevenlabs":
        deps.append('"elevenlabs>=1.0"')
    elif tts == "edge-tts":
        deps.append('"edge-tts>=6.0"')
    if llm == "openai":
        deps.append('"openai>=1.0"')
    elif llm == "anthropic":
        deps.append('"anthropic>=0.30"')
    elif llm == "groq":
        deps.append('"groq>=0.13"')
    deps_str = ",\n    ".join(deps)
    return (
        f'[project]\nname = "{name}"\nversion = "0.1.0"\n'
        f'description = "Production-grade voice agent generated by Voice Agent Workbench"\n'
        f'requires-python = ">=3.11"\ndependencies = [\n    {deps_str},\n]\n\n'
        f'[project.scripts]\nrun-agent = "agent:main"\nrun-server = "server:main"\n'
    )


