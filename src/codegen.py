_SERVER_PY = r'''"""WebSocket server with health, metrics, and graceful shutdown."""

from __future__ import annotations

import asyncio
import json
import os
import signal
import time

import structlog
import websockets
from websockets.server import serve

from agent import VoiceAgent

logger = structlog.get_logger()

ACTIVE_CONNECTIONS: dict[str, VoiceAgent] = {}
SERVER_START = time.monotonic()


async def handle_connection(ws):
    """Handle a single WebSocket client connection."""
    client_id = str(id(ws))
    agent = VoiceAgent()
    ACTIVE_CONNECTIONS[client_id] = agent
    logger.info("client_connected", client_id=client_id, active=len(ACTIVE_CONNECTIONS))

    try:
        async for message in ws:
            try:
                data = json.loads(message)
            except json.JSONDecodeError:
                logger.warning("invalid_json", client_id=client_id)
                continue

            msg_type = data.get("type")

            if msg_type == "audio":
                audio = bytes.fromhex(data.get("data", ""))
                text, audio_out = await agent.handle_audio(audio)

                if text and audio_out:
                    await ws.send(json.dumps({
                        "type": "audio",
                        "data": audio_out.hex(),
                    }))
                    await ws.send(json.dumps({
                        "type": "text",
                        "data": text,
                    }))
                elif text:
                    await ws.send(json.dumps({
                        "type": "text",
                        "data": text,
                    }))

            elif msg_type == "config":
                await ws.send(json.dumps({
                    "type": "ready",
                    "languages": LANGUAGES,
                }))

            elif msg_type == "metrics":
                await ws.send(json.dumps({
                    "type": "metrics",
                    "data": agent.metrics.summary(),
                }))

    except websockets.exceptions.ConnectionClosed:
        pass
    except Exception as e:
        logger.error("client_error", client_id=client_id, error=str(e))
    finally:
        ACTIVE_CONNECTIONS.pop(client_id, None)
        logger.info("client_disconnected", client_id=client_id, active=len(ACTIVE_CONNECTIONS))


async def health_handler(ws):
    """Health check endpoint."""
    uptime = time.monotonic() - SERVER_START
    await ws.send(json.dumps({
        "status": "ok",
        "uptime_seconds": round(uptime, 1),
        "active_connections": len(ACTIVE_CONNECTIONS),
    }))
    await ws.close()


async def metrics_handler(ws):
    """Aggregate metrics from all connections."""
    all_metrics = [a.metrics.summary() for a in ACTIVE_CONNECTIONS.values()]
    await ws.send(json.dumps({
        "connections": len(ACTIVE_CONNECTIONS),
        "sessions": all_metrics,
    }))
    await ws.close()


async def health_http(reader, writer):
    """HTTP health endpoint for load balancers."""
    await reader.read(4096)
    uptime = time.monotonic() - SERVER_START
    body = json.dumps({
        "status": "ok",
        "uptime_seconds": round(uptime, 1),
        "active_connections": len(ACTIVE_CONNECTIONS),
    })
    response = (
        "HTTP/1.1 200 OK\r\n"
        "Content-Type: application/json\r\n"
        f"Content-Length: {len(body)}\r\n"
        "\r\n"
        f"{body}"
    )
    writer.write(response.encode())
    await writer.drain()
    writer.close()


LANGUAGES = {LANGUAGES}


async def main():
    """Start WebSocket + HTTP servers with graceful shutdown."""
    stop = asyncio.Event()

    def _signal_handler():
        logger.info("shutdown_requested")
        stop.set()

    loop = asyncio.get_running_loop()
    for sig in (signal.SIGINT, signal.SIGTERM):
        try:
            loop.add_signal_handler(sig, _signal_handler)
        except NotImplementedError:
            pass

    ws_port = int(os.getenv("WS_PORT", "8080"))
    http_port = int(os.getenv("HTTP_PORT", "8081"))

    async with serve(handle_connection, "0.0.0.0", ws_port):
        logger.info("ws_server_started", port=ws_port)

        http_server = await asyncio.start_server(health_http, "0.0.0.0", http_port)
        logger.info("http_server_started", port=http_port, endpoints="/health /metrics")

        await stop.wait()

        http_server.close()
        await http_server.wait_closed()
        logger.info("shutdown_complete")


if __name__ == "__main__":
    asyncio.run(main())
'''


