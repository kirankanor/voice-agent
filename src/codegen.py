_AGENT_PY = r'''"""Voice agent with production-grade error handling and streaming."""

from __future__ import annotations

import asyncio
import time
import structlog
from dataclasses import dataclass, field

from providers.stt import STTProvider
from providers.tts import TTSProvider
from providers.llm import LLMProvider
from providers.vad import VADProvider

logger = structlog.get_logger()

LANGUAGES = {LANGUAGES}
SYSTEM_PROMPT = """You are a helpful voice assistant. Be concise and conversational."""


@dataclass
class Metrics:
    """Tracks per-session metrics."""
    stt_latency_ms: list[float] = field(default_factory=list)
    llm_latency_ms: list[float] = field(default_factory=list)
    tts_latency_ms: list[float] = field(default_factory=list)
    total_tokens: int = 0
    total_cost: float = 0.0
    errors: int = 0

    def summary(self) -> dict:
        return {
            "stt_avg_ms": round(sum(self.stt_latency_ms) / max(len(self.stt_latency_ms), 1), 1),
            "llm_avg_ms": round(sum(self.llm_latency_ms) / max(len(self.llm_latency_ms), 1), 1),
            "tts_avg_ms": round(sum(self.tts_latency_ms) / max(len(self.tts_latency_ms), 1), 1),
            "total_tokens": self.total_tokens,
            "total_cost": round(self.total_cost, 6),
            "errors": self.errors,
        }


class VoiceAgent:
    """Production voice agent with retry, streaming, and metrics."""

    MAX_HISTORY = 20
    MAX_RETRIES = 3
    RETRY_BASE_DELAY = 0.5

    def __init__(self):
        self.stt = STTProvider()
        self.tts = TTSProvider()
        self.llm = LLMProvider()
        self.vad = VADProvider()
        self.metrics = Metrics()
        self._history: list[dict] = []

    async def _retry(self, fn, *args, **kwargs):
        """Execute with exponential backoff retry."""
        last_err = None
        for attempt in range(self.MAX_RETRIES):
            try:
                return await fn(*args, **kwargs)
            except Exception as e:
                last_err = e
                self.metrics.errors += 1
                delay = self.RETRY_BASE_DELAY * (2 ** attempt)
                logger.warning("retry", attempt=attempt + 1, error=str(e), delay=delay)
                await asyncio.sleep(delay)
        raise last_err

    async def transcribe(self, audio: bytes) -> str | None:
        """Transcribe audio with retry and timing."""
        start = time.monotonic()
        try:
            text = await self._retry(self.stt.transcribe, audio)
            elapsed = (time.monotonic() - start) * 1000
            self.metrics.stt_latency_ms.append(elapsed)
            logger.info("stt_complete", text=text[:50] if text else "", latency_ms=round(elapsed, 1))
            return text
        except Exception as e:
            logger.error("stt_failed", error=str(e))
            return None

    async def generate_response(self, text: str) -> str | None:
        """Generate LLM response with retry and timing."""
        start = time.monotonic()
        try:
            response = await self._retry(
                self.llm.generate, text, SYSTEM_PROMPT, self._history
            )
            elapsed = (time.monotonic() - start) * 1000
            self.metrics.llm_latency_ms.append(elapsed)
            logger.info("llm_complete", response=response[:50] if response else "", latency_ms=round(elapsed, 1))
            return response
        except Exception as e:
            logger.error("llm_failed", error=str(e))
            return None

    async def synthesize(self, text: str) -> bytes | None:
        """Synthesize speech with retry and timing."""
        start = time.monotonic()
        try:
            audio = await self._retry(self.tts.synthesize, text)
            elapsed = (time.monotonic() - start) * 1000
            self.metrics.tts_latency_ms.append(elapsed)
            logger.info("tts_complete", text_len=len(text), latency_ms=round(elapsed, 1))
            return audio
        except Exception as e:
            logger.error("tts_failed", error=str(e))
            return None

    async def handle_audio(self, audio: bytes) -> tuple[str | None, bytes | None]:
        """Full pipeline: VAD -> STT -> LLM -> TTS. Returns (text, audio)."""
        if not await self.vad.detect(audio):
            return None, None

        text = await self.transcribe(audio)
        if not text:
            return None, None

        self._history.append({"role": "user", "content": text})
        if len(self._history) > self.MAX_HISTORY:
            self._history = self._history[-self.MAX_HISTORY:]

        response = await self.generate_response(text)
        if not response:
            return text, None

        self._history.append({"role": "assistant", "content": response})
        audio_data = await self.synthesize(response)
        return text, audio_data
'''


